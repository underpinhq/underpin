// Writes `src/generated/`: one ES module per flag and per browser logo, each holding its image as a
// data URI, the maps that load them with `import()`, and the OS and device glyphs. A bundler then
// splits every image into its own chunk, and nothing loads from another origin.
//
// Sources, all from this package's dev dependencies or `assets/`:
// - flags: flag-icons (MIT), the 4:3 set
// - browser logos: `assets/browsers`, from alrra/browser-logos (MIT)
// - OS marks: Simple Icons (CC0-1.0); Windows is drawn here, since Simple Icons drops Microsoft marks
// - device glyphs: Lucide (ISC)
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises"
import { createRequire } from "node:module"
import path from "node:path"

const root = path.join(import.meta.dir, "..")
const out = path.join(root, "src/generated")
const require = createRequire(import.meta.url)

function packageDir(name: string) {
  return path.dirname(require.resolve(`${name}/package.json`))
}

function dataUri(type: string, bytes: Buffer) {
  return `data:${type};base64,${bytes.toString("base64")}`
}

function imageModule(source: string, uri: string) {
  return `// Generated by scripts/generate.ts from ${source}.\nconst image: string = ${JSON.stringify(uri)}\nexport default image\n`
}

function loaderMap(name: string, folder: string, keys: string[]) {
  const entries = keys.map(
    key => `  ${JSON.stringify(key)}: () => import("./${folder}/${key}.js"),`,
  )
  return [
    "// Generated by scripts/generate.ts.",
    `export const ${name}: Record<string, () => Promise<{ default: string }>> = {`,
    ...entries,
    "}",
    "",
  ].join("\n")
}

async function writeImages(
  folder: string,
  files: string[],
  read: (file: string) => Promise<[string, string]>,
) {
  await mkdir(path.join(out, folder), { recursive: true })
  const keys: string[] = []

  for (const file of files) {
    const [key, contents] = await read(file)
    await writeFile(path.join(out, folder, `${key}.ts`), contents)
    keys.push(key)
  }

  return keys.sort()
}

/** The `d` of every `<path>` in a Simple Icons SVG. */
async function simpleIcon(slug: string) {
  const svg = await readFile(path.join(packageDir("simple-icons"), "icons", `${slug}.svg`), "utf8")
  return [...svg.matchAll(/<path d="([^"]+)"/g)].map(match => match[1])
}

/** The child elements of a Lucide SVG, as tag names and attributes. */
async function lucideIcon(name: string) {
  const svg = await readFile(path.join(packageDir("lucide-static"), "icons", `${name}.svg`), "utf8")
  return [...svg.matchAll(/<(path|rect|line|circle|polyline)\s([^>]*?)\/>/g)].map(
    ([, tag, attributes]) => ({
      tag,
      attributes: Object.fromEntries(
        [...(attributes ?? "").matchAll(/([\w-]+)="([^"]*)"/g)].map(([, key, value]) => [
          key,
          value,
        ]),
      ),
    }),
  )
}

await rm(out, { recursive: true, force: true })

const flagDir = path.join(packageDir("flag-icons"), "flags/4x3")
const flagFiles = (await readdir(flagDir)).filter(file => file.endsWith(".svg"))
const flagKeys = await writeImages("flags", flagFiles, async file => [
  file.replace(/\.svg$/, ""),
  imageModule(
    "flag-icons (MIT)",
    dataUri("image/svg+xml", await readFile(path.join(flagDir, file))),
  ),
])

const logoDir = path.join(root, "assets/browsers")
const logoFiles = (await readdir(logoDir)).filter(file => file.endsWith(".png"))
const logoKeys = await writeImages("browsers", logoFiles, async file => [
  file.replace(/\.png$/, ""),
  imageModule(
    "alrra/browser-logos (MIT)",
    dataUri("image/png", await readFile(path.join(logoDir, file))),
  ),
])

const osMarks = {
  apple: await simpleIcon("apple"),
  android: await simpleIcon("android"),
  linux: await simpleIcon("linux"),
  ubuntu: await simpleIcon("ubuntu"),
  chrome: await simpleIcon("googlechrome"),
  harmonyos: await simpleIcon("harmonyos"),
  fedora: await simpleIcon("fedora"),
  debian: await simpleIcon("debian"),
  freebsd: await simpleIcon("freebsd"),
  playstation: await simpleIcon("playstation"),
  // Four panes, drawn here.
  windows: ["M0 0h11.4v11.4H0zM12.6 0H24v11.4H12.6zM0 12.6h11.4V24H0zM12.6 12.6H24V24H12.6z"],
}

const deviceGlyphs = {
  desktop: await lucideIcon("monitor"),
  mobile: await lucideIcon("smartphone"),
  tablet: await lucideIcon("tablet"),
  smarttv: await lucideIcon("tv"),
  console: await lucideIcon("gamepad-2"),
  wearable: await lucideIcon("watch"),
  xr: await lucideIcon("glasses"),
  globe: await lucideIcon("globe"),
  browser: await lucideIcon("app-window"),
}

await writeFile(path.join(out, "flags.ts"), loaderMap("FLAG_LOADERS", "flags", flagKeys))
await writeFile(path.join(out, "browsers.ts"), loaderMap("LOGO_LOADERS", "browsers", logoKeys))
await writeFile(
  path.join(out, "glyphs.ts"),
  [
    "// Generated by scripts/generate.ts.",
    "/** Filled 24×24 marks from Simple Icons (CC0-1.0), as path data. */",
    `export const OS_MARKS: Record<string, string[]> = ${JSON.stringify(osMarks, null, 2)}`,
    "",
    "/** Stroked 24×24 glyphs from Lucide (ISC), as elements. */",
    `export const LINE_GLYPHS: Record<string, { tag: string; attributes: Record<string, string> }[]> = ${JSON.stringify(deviceGlyphs, null, 2)}`,
    "",
  ].join("\n"),
)

console.log(`Generated ${flagKeys.length} flags, ${logoKeys.length} browser logos and the glyphs.`)
